package render

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"image"
	_ "image/jpeg" // register JPEG dimension decoding
	_ "image/png"  // register PNG dimension decoding
	"io"
	"os"
	"strings"

	"github.com/20Youssef10/golab/internal/platform"
)

// DefaultImageMaxBytes caps inline image payloads at 8 MiB. Larger images are
// still written to --output-image (or a temp file) and reported by path.
const DefaultImageMaxBytes = 8 << 20

// ImageConfig controls Kitty image emission and the file fallback used when
// stdout is not a TTY (the --output-image flag is TargetPath).
type ImageConfig struct {
	// TargetPath is the --output-image destination. Empty means a temp file.
	TargetPath string
	// TempDir is the directory for the fallback temp file. Empty means
	// platform.TempDir().
	TempDir string
	// IsTTY overrides TTY detection (for tests). Nil means platform.IsStdoutTTY.
	IsTTY func() bool
	// Env overrides environment lookups for terminal negotiation (for tests).
	Env func(string) string
	// Stderr receives the "size cap" notice. Nil means os.Stderr.
	Stderr io.Writer
	// MaxBytes caps inline payloads. <=0 uses DefaultImageMaxBytes.
	MaxBytes int64
	// MaxWidth/MaxHeight cap inline images when the format exposes dimensions.
	// Zero means no pixel cap.
	MaxWidth, MaxHeight int
	// Protocol overrides negotiation: kitty, iterm2 or none. Empty is auto.
	Protocol string
}

type imageFormat struct {
	kitty string // Kitty graphics protocol value for f=
	ext   string // filename extension for the fallback file
}

func imageFormatFor(format string) (imageFormat, error) {
	switch strings.ToLower(strings.TrimPrefix(strings.TrimSpace(format), "image/")) {
	case "png":
		return imageFormat{kitty: "100", ext: "png"}, nil
	case "jpeg", "jpg":
		return imageFormat{kitty: "99", ext: "jpeg"}, nil
	default:
		return imageFormat{}, fmt.Errorf("render: unsupported image format %q", format)
	}
}

// Image emits data using the Kitty graphics protocol when stdout is a TTY and
// always writes the image to a file, reporting its path. When stdout is not a
// TTY the escape sequence is suppressed (it would corrupt piped output) but the
// file fallback remains available, matching upstream handle_image/print_kitty.
func Image(w io.Writer, data []byte, format string) error {
	return ImageWithConfig(w, data, format, ImageConfig{})
}

// ImageWithConfig is Image with an explicit configuration.
func ImageWithConfig(w io.Writer, data []byte, format string, cfg ImageConfig) error {
	if w == nil {
		return fmt.Errorf("render: nil image writer")
	}
	fmtInfo, err := imageFormatFor(format)
	if err != nil {
		return err
	}

	isTTY := platform.IsStdoutTTY()
	if cfg.IsTTY != nil {
		isTTY = cfg.IsTTY()
	}
	env := os.Getenv
	if cfg.Env != nil {
		env = cfg.Env
	}
	stderr := io.Writer(os.Stderr)
	if cfg.Stderr != nil {
		stderr = cfg.Stderr
	}
	protocol := negotiateImageProtocol(cfg, isTTY, env)
	oversize, reason := imageExceedsCaps(data, cfg)
	if protocol != "none" && !oversize {
		var buf bytes.Buffer
		switch protocol {
		case "iterm2":
			// OSC 1337 with inline=1; the name is generated by us, never
			// taken from remote output, and is base64-encoded.
			buf.WriteString("\n\x1b]1337;File=inline=1;name=")
			buf.WriteString(base64.StdEncoding.EncodeToString([]byte("image." + fmtInfo.ext)))
			buf.WriteByte(':')
			enc := base64.NewEncoder(base64.StdEncoding, &buf)
			if _, err := enc.Write(data); err != nil {
				return fmt.Errorf("render: encode iterm2 image: %w", err)
			}
			if err := enc.Close(); err != nil {
				return fmt.Errorf("render: encode iterm2 image: %w", err)
			}
			buf.WriteString("\x07\n")
		default:
			buf.WriteString("\n\x1b_Ga=T,f=")
			buf.WriteString(fmtInfo.kitty)
			buf.WriteByte(';')
			enc := base64.NewEncoder(base64.StdEncoding, &buf)
			if _, err := enc.Write(data); err != nil {
				return fmt.Errorf("render: encode kitty image: %w", err)
			}
			if err := enc.Close(); err != nil {
				return fmt.Errorf("render: encode kitty image: %w", err)
			}
			buf.WriteString("\x1b\\\n")
		}
		if err := writeAll(w, buf.Bytes()); err != nil {
			return fmt.Errorf("render: write %s image: %w", protocol, err)
		}
	}

	var saved string
	if cfg.TargetPath != "" {
		saved = cfg.TargetPath
		if err := os.WriteFile(saved, data, 0o600); err != nil {
			return fmt.Errorf("render: save image to %q: %w", saved, err)
		}
	} else {
		dir := cfg.TempDir
		if dir == "" {
			dir = platform.TempDir()
		}
		f, err := os.CreateTemp(dir, "colab-image-*."+fmtInfo.ext)
		if err != nil {
			return fmt.Errorf("render: create temp image: %w", err)
		}
		tempPath := f.Name()
		saved = tempPath
		// The fallback file is a transient render artifact: the displayed
		// image is carried inline by the escape sequence above, and the path
		// is reported before this deferred removal runs. A user-requested
		// --output-image save (TargetPath above) is never removed.
		defer func() { _ = os.Remove(tempPath) }()
		if _, err := f.Write(data); err != nil {
			_ = f.Close()
			return fmt.Errorf("render: write temp image: %w", err)
		}
		if err := f.Close(); err != nil {
			return fmt.Errorf("render: close temp image: %w", err)
		}
	}

	// The path may come from a remote-controlled --output-image value. Strip
	// OSC/DCS/query sequences before printing it, but keep ordinary text.
	if _, err := fmt.Fprintf(w, "\n[Image saved to: %s]\n", Sanitize(saved)); err != nil {
		return fmt.Errorf("render: report image path: %w", err)
	}
	if oversize && isTTY && protocol != "none" {
		if _, err := fmt.Fprintf(stderr, "[colab] image exceeds %s; saved to %s\n",
			reason, Sanitize(saved)); err != nil {
			return fmt.Errorf("render: report image cap: %w", err)
		}
	}
	return nil
}

// negotiateImageProtocol prefers Kitty on a TTY for backwards compatibility,
// falls back to iTerm2 for iTerm/WezTerm, and emits nothing when stdout is a
// pipe. An explicit Protocol always wins except off TTY.
func negotiateImageProtocol(cfg ImageConfig, isTTY bool, env func(string) string) string {
	if !isTTY {
		return "none"
	}
	switch strings.ToLower(strings.TrimSpace(cfg.Protocol)) {
	case "kitty", "iterm2", "none":
		return strings.ToLower(strings.TrimSpace(cfg.Protocol))
	}
	switch env("TERM_PROGRAM") {
	case "iTerm.app", "WezTerm":
		return "iterm2"
	}
	return "kitty"
}

// imageExceedsCaps checks both the byte cap and, when the format exposes them,
// the pixel dimensions. DecodeConfig reads only the header, never the payload.
func imageExceedsCaps(data []byte, cfg ImageConfig) (bool, string) {
	maxBytes := cfg.MaxBytes
	if maxBytes <= 0 {
		maxBytes = DefaultImageMaxBytes
	}
	if int64(len(data)) > maxBytes {
		return true, fmt.Sprintf("the %d-byte inline cap", maxBytes)
	}
	if cfg.MaxWidth > 0 || cfg.MaxHeight > 0 {
		if dc, _, err := image.DecodeConfig(bytes.NewReader(data)); err == nil {
			if (cfg.MaxWidth > 0 && dc.Width > cfg.MaxWidth) ||
				(cfg.MaxHeight > 0 && dc.Height > cfg.MaxHeight) {
				return true, fmt.Sprintf("the %dx%d pixel cap", cfg.MaxWidth, cfg.MaxHeight)
			}
		}
	}
	return false, ""
}
