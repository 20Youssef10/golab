package cli

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/spf13/cobra"

	"github.com/20Youssef10/golab/internal/logx"
)

// initGolabYAML is a strict-schema budget profile. It includes a named
// `default` profile because the billable-command guard resolves that name by
// default; without it LoadProfile would report ErrProfileNotFound and the
// scaffold would silently do nothing. [tier5]
const initGolabYAML = `# golab workspace configuration — generated by ` + "`golab init`" + `.
# Thresholds are compute units (CU); golab never converts CU into money.
# Set enforce to false for advisory-only warnings.
version: 1
defaults:
  budget:
    max_balance: 100
    max_hourly: 20
    enforce: true
profiles:
  default:
    budget:
      max_balance: 100
      max_hourly: 20
      enforce: true
`

const initGolabIgnore = `# Patterns golab ignores when syncing workspace files.
.git/
__pycache__/
*.pyc
.ipynb_checkpoints/
.venv/
venv/
node_modules/
dist/
*_output.ipynb
`

type scaffoldFile struct {
	name    string
	content string
}

// writeScaffoldFile writes one file atomically with owner-only permissions.
func writeScaffoldFile(name, content string) error {
	dir := filepath.Dir(name)
	tmp, err := os.CreateTemp(dir, ".golab-init-*")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	defer func() { _ = os.Remove(tmpPath) }()
	if err := tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.WriteString(content); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpPath, name)
}

func initCommand() *cobra.Command {
	var force bool
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Scaffold golab.yaml and .golabignore in the current directory",
		Args:  noArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			d := depsOf(cmd)
			files := []scaffoldFile{
				{name: "golab.yaml", content: initGolabYAML},
				{name: ".golabignore", content: initGolabIgnore},
			}
			// Check BOTH targets before writing either one: a conflict must
			// never leave a half-scaffolded workspace.
			for _, f := range files {
				if _, err := os.Lstat(f.name); err == nil {
					if !force {
						return exitf(1, "[colab] init: %s already exists. Use --force to overwrite.", f.name)
					}
				} else if !os.IsNotExist(err) {
					return exitf(1, "[colab] init: cannot inspect %s: %s", f.name, logx.Redact(err.Error()))
				}
			}
			for _, f := range files {
				if err := writeScaffoldFile(f.name, f.content); err != nil {
					return exitf(1, "[colab] init: could not write %s: %s", f.name, logx.Redact(err.Error()))
				}
				fmt.Fprintf(d.Stderr, "[colab] Created %s.\n", f.name)
			}
			return nil
		},
	}
	cmd.Flags().BoolVar(&force, "force", false, "Overwrite existing golab.yaml and .golabignore")
	return cmd
}

// RegisterInitCommands is the integration hook for the shared register.go.
func RegisterInitCommands(root *cobra.Command) { root.AddCommand(initCommand()) }
